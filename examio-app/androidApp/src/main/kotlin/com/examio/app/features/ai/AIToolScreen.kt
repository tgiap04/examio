@Composable
fun AIToolScreen(modifier: Modifier = Modifier) {
    var selectedTypes by remember { mutableStateOf(setOf("Trắc nghiệm")) }
    var count by remember { mutableStateOf("5") }
    var keywords by remember { mutableStateOf("") }
    var generated by remember { mutableStateOf(false) }
    val types = listOf("Trắc nghiệm", "Điền từ", "Đúng/Sai", "Điền đoạn", "Đáp án đúp", "Biểu mẫu")

    LazyColumn(
        modifier = modifier.fillMaxSize().background(Color(0xFFFFF7F1)).padding(20.dp),
        verticalArrangement = Arrangement.spacedBy(16.dp),
    ) {
        item {
            Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
                Text("Công cụ AI", style = MaterialTheme.typography.headlineLarge, color = Color(0xFF2D211B))
                Text("Upload PDF, chọn dạng câu hỏi và tạo bộ đề trong vài giây.", color = MaterialTheme.colorScheme.onSurfaceVariant)
            }
        }
        item {
            FlowChips(types, selectedTypes) { type ->
                selectedTypes = if (type in selectedTypes) selectedTypes - type else selectedTypes + type
            }
        }
        item { PdfUploadZone() }
        item {
            Row(horizontalArrangement = Arrangement.spacedBy(12.dp), modifier = Modifier.fillMaxWidth()) {
                OutlinedTextField(value = count, onValueChange = { count = it.filter(Char::isDigit).take(2) }, label = { Text("Số lượng") }, modifier = Modifier.weight(0.8f))
                OutlinedTextField(value = keywords, onValueChange = { keywords = it }, label = { Text("Từ khóa") }, modifier = Modifier.weight(1.2f))
            }
        }
        item {
            Button(onClick = { generated = true }, modifier = Modifier.fillMaxWidth(), enabled = selectedTypes.isNotEmpty()) {
                Text("Bắt đầu")
            }
        }
        if (generated) {
            item { Text("Preview: ${count.ifBlank { "5" }} câu hỏi đã tạo", style = MaterialTheme.typography.titleMedium) }
            items(sampleQuestions) { question -> GeneratedQuestionCard(question) }
        }
    }
}

@Composable
private fun FlowChips(types: List<String>, selectedTypes: Set<String>, onToggle: (String) -> Unit) {
    Column(verticalArrangement = Arrangement.spacedBy(8.dp)) {
        types.chunked(3).forEach { row ->
            Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                row.forEach { type ->
                    FilterChip(selected = type in selectedTypes, onClick = { onToggle(type) }, label = { Text(type) })
                }
            }
        }
    }
}

@Composable
private fun PdfUploadZone() {
    Card(
        modifier = Modifier.fillMaxWidth().clickable { },
        shape = RoundedCornerShape(24.dp),
        border = BorderStroke(1.dp, Color(0x55CC785C)),
        colors = CardDefaults.cardColors(containerColor = Color.White),
    ) {
        Column(modifier = Modifier.fillMaxWidth().padding(24.dp), horizontalAlignment = Alignment.CenterHorizontally, verticalArrangement = Arrangement.spacedBy(10.dp)) {
            Icon(Icons.Outlined.UploadFile, contentDescription = null, tint = Color(0xFFCC785C))
            Text("Nhấn để chọn file PDF", style = MaterialTheme.typography.titleMedium)
            Text("Hỗ trợ PDF tối đa 10MB", color = MaterialTheme.colorScheme.onSurfaceVariant)
        }
    }
}

@Composable
private fun GeneratedQuestionCard(question: String) {
    Card(shape = RoundedCornerShape(18.dp), colors = CardDefaults.cardColors(containerColor = Color.White)) {
        Row(modifier = Modifier.fillMaxWidth().padding(16.dp), horizontalArrangement = Arrangement.spacedBy(12.dp)) {
            Icon(Icons.Outlined.Description, contentDescription = null, tint = Color(0xFFCC785C))
            Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
                Text("Trắc nghiệm", color = Color(0xFFCC785C), style = MaterialTheme.typography.labelMedium)
                Text(question, style = MaterialTheme.typography.bodyLarge)
                Text("Đáp án đúng: B", color = MaterialTheme.colorScheme.onSurfaceVariant)
            }
        }
    }
}

private val sampleQuestions = listOf(
    "Khái niệm chính của tài liệu này là gì?",
    "Yếu tố nào ảnh hưởng trực tiếp tới kết quả học tập?",
    "Phát biểu nào sau đây là đúng theo nội dung PDF?",
)
