/**
 * Emits examio-fe/src/types/permissions.generated.ts from the permission
 * catalog (libs/auth-jwt/src/permissions.ts). CI re-runs this and fails on a
 * git diff, so the FE union can never drift from the backend catalog.
 *
 * Usage: yarn gen:fe-permissions
 */
import { writeFileSync } from 'fs';
import { resolve } from 'path';
import { PERMISSIONS, ROLE_PERMISSIONS } from '../libs/auth-jwt/src/permissions';

const OUTPUT = resolve(
    __dirname,
    '../../examio-fe/src/types/permissions.generated.ts',
);

function render(): string {
    const lines: string[] = [
        '// DO NOT EDIT. Generated by examio-be/scripts/gen-fe-permissions.ts',
        '// from libs/auth-jwt/src/permissions.ts (run `yarn gen:fe-permissions`).',
        '',
        'export const PERMISSIONS = {',
    ];
    for (const [key, value] of Object.entries(PERMISSIONS)) {
        lines.push(`  ${key}: "${value}",`);
    }
    lines.push(
        '} as const;',
        '',
        'export type Permission = (typeof PERMISSIONS)[keyof typeof PERMISSIONS];',
        '',
    );
    const roles = Object.keys(ROLE_PERMISSIONS);
    lines.push(`export type Role = ${roles.map((r) => `"${r}"`).join(' | ')};`, '');
    lines.push('export const ROLE_PERMISSIONS: Record<Role, readonly Permission[]> = {');
    for (const role of roles) {
        lines.push(`  ${role}: [`);
        for (const permission of ROLE_PERMISSIONS[role as keyof typeof ROLE_PERMISSIONS]) {
            lines.push(`    "${permission}",`);
        }
        lines.push('  ],');
    }
    lines.push('};', '');
    return lines.join('\n');
}

writeFileSync(OUTPUT, render(), 'utf8');
console.log(`wrote ${OUTPUT}`);
