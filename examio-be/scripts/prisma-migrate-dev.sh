#!/usr/bin/env bash
# Creates the next migration of one service from its Prisma schema.
#
#   PRISMA_ADMIN_URL=postgresql://examio:examio@127.0.0.1:5432/examio \
#     scripts/prisma-migrate-dev.sh <auth|finance|admin|exam|studyroom|vocabulary|document> <name>
#
# The history is replayed into a throwaway SUPERUSER shadow database
# (examio_shadow_<svc>) and diffed against the schema, so no service database is
# touched and no `_prisma_migrations` table is ever owned by a superuser.
# Review the SQL, then hand-edit what Prisma cannot express (partial outbox
# index, `extensions.vector` columns). Production applies it with
# `prisma migrate deploy --schema <path>` as the service role.
set -euo pipefail
svc="${1:?service required (auth|finance|admin|exam|studyroom|vocabulary|document)}"
name="${2:?migration name required, e.g. init}"
cd "$(dirname "$0")/.."

schema="$(scripts/prisma-schema-path.sh "$svc")"
# Prisma looks for migrations/ next to a schema FILE, or INSIDE a multi-file schema folder.
if [[ -d "$schema" ]]; then dir="$schema/migrations"; else dir="$(dirname "$schema")/migrations"; fi
mkdir -p "$dir"
[[ -f "$dir/migration_lock.toml" ]] || cat > "$dir/migration_lock.toml" <<'LOCK'
# Please do not edit this file manually
# It should be added in your version-control system (e.g., Git)
provider = "postgresql"
LOCK

shadow_url="$(node scripts/prisma-shadow-db.cjs "$svc")"
export DATABASE_URL="$shadow_url"
sql="$(mktemp)"
trap 'rm -f "$sql"' EXIT
node_modules/.bin/prisma migrate diff \
    --from-migrations "$dir" \
    --to-schema-datamodel "$schema" \
    --shadow-database-url "$shadow_url" \
    --script > "$sql"

if grep -q "This is an empty migration" "$sql"; then
    echo "No schema changes for $svc: nothing to create."
    exit 0
fi
stamp="$(date -u +%Y%m%d%H%M%S)"
mkdir -p "$dir/${stamp}_${name}"
cp "$sql" "$dir/${stamp}_${name}/migration.sql"
echo "Created $dir/${stamp}_${name}/migration.sql. Review and hand-edit it before committing."
