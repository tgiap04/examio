# .generated/compose/<x>.env-masks.yaml: the app containers mount kmaedu-be (or kmaedu-fe) whole, and Nest,
# Prisma, Vite - or any package script `yarn install` runs - can read an env file there (a REMOTE database,
# production deploy secrets). So EVERY container that mounts a tree gets, for EVERY env file that EXISTS in
# it, the read-only .generated/empty.env on top, and kmaedu-be/deploy/env (the real per-service secrets)
# under an empty tmpfs. Existence is tested with -e only; contents are never opened. Generated rather than
# static: a bind-mount target that does not exist is created by Docker in the host tree (an empty file,
# root-owned on Linux). A file added later is masked from the next `./project up` on. bash 3.2 safe.
# shellcheck shell=bash

# _mask_spec <compose name>: "<service> be|fe" lines. Every deploy compose file must be listed: a new one
# dies here instead of silently running without masks. infra and ai mount no source tree.
_mask_spec() {
  case "$1" in
    auth | admin | content | assessment | study-room | vocabulary | document | ai-chat)
      printf '%s be\n' "$1" "$1-migrate" ;;
    r2 | seed) printf '%s be\n' "$1" ;;
    gateway) printf '%s be\n' gateway-a gateway-b ;;
    dev-extras) printf '%s\n' "deps be" "fe fe" ;;
    infra | ai) ;;
    *) die "no host env masks defined for compose/$1.yml: list its services that mount kmaedu-be or kmaedu-fe in _mask_spec (lib/render-host-env-masks.sh)" ;;
  esac
}

# _env_files <tree root> <dir...>: relative paths of the env files (.env, .env.*, never *.example) that
# exist in each dir of the tree. Paths land in double-quoted YAML: an unsafe character dies.
_env_files() {
  local root="$1" dir f
  shift
  for dir in "$@"; do
    for f in "$root/$dir"/.env "$root/$dir"/.env.*; do
      case "$f" in *.example) continue ;; esac
      [ -f "$f" ] || [ -L "$f" ] || continue
      check_path_chars "$f"
      f="${f#"$root"/}"
      printf '%s\n' "${f#./}"
    done
  done
}

# _be_env_files / _fe_env_files: computed once per render (globs over the trees).
_be_env_files() {
  local dirs=". deploy" d
  for d in "$BE_DIR"/apps/*/; do
    [ -d "$d" ] || continue
    d="${d%/}"
    dirs="$dirs apps/${d##*/}"
  done
  # shellcheck disable=SC2086  # dir names are checked by _env_files
  _env_files "$BE_DIR" $dirs
  # Rendered RabbitMQ users of the deploy stack (password hashes): never needed by a dev container.
  [ ! -f "$BE_DIR/deploy/rabbitmq/definitions.json" ] || printf '%s\n' deploy/rabbitmq/definitions.json
}
_fe_env_files() { _env_files "$FE_DIR" .; }

# _mask_bind <container path>: one long-syntax mount of empty.env (colons in names stay safe).
_mask_bind() {
  printf '            - type: bind\n              source: "%s"\n              target: "%s"\n              read_only: true\n' \
    "$GEN_DIR/empty.env" "$1"
}

# _service_masks <be|fe>: the volume lines of one service (may be empty).
_service_masks() {
  local f files="$_BE_FILES" root=/workspace
  [ "$1" = be ] || files="$_FE_FILES" root=/workspace-fe
  while IFS= read -r f; do
    [ -z "$f" ] || _mask_bind "$root/$f"
  done <<EOF
$files
EOF
  [ "$1" = be ] || return 0
  [ ! -d "$BE_DIR/deploy/env" ] || printf '            - type: tmpfs\n              target: /workspace/deploy/env\n'
}

# _masks_body <spec>: a compose fragment, empty when no service has anything to cover.
_masks_body() {
  local svc tree lines out=""
  while read -r svc tree; do
    [ -n "$svc" ] || continue
    lines="$(_service_masks "$tree")"
    [ -z "$lines" ] || out="$out    $svc:"$'\n'"        volumes:"$'\n'"$lines"$'\n'
  done <<EOF
$1
EOF
  [ -z "$out" ] || printf 'services:\n%s' "$out"
}

# masks_file <compose name>: path of its generated mask fragment.
masks_file() { printf '%s\n' "$GEN_DIR/compose/$1.env-masks.yaml"; }

# render_env_masks <compose names...>: write each non-empty fragment, drop stale ones.
render_env_masks() {
  local name spec body dest
  _BE_FILES="$(_be_env_files)" || exit 1
  _FE_FILES="$(_fe_env_files)" || exit 1
  mkdir -p "$GEN_DIR/compose" || die "cannot create $GEN_DIR/compose"
  for name in "$@"; do
    spec="$(_mask_spec "$name")" || exit 1
    dest="$(masks_file "$name")"
    body="$(_masks_body "$spec")"
    if [ -n "$body" ]; then
      printf '# Generated by docker-development - do not edit.\n%s\n' "$body" | write_file_atomic "$dest" ||
        die "writing $dest failed"
    else
      rm -f "$dest"
    fi
  done
}
