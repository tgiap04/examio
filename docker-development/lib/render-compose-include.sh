# .generated/compose.yaml: Compose `include` of every deploy/compose/<x>.yml (list read from
# deploy/docker-compose.yml) merged with docker-development/compose/<x>.dev.yaml, plus dev-extras.yaml.
# deploy/docker-compose.yml itself is NOT included: its nested includes carry no env_file, so Compose
# would load deploy/.env (real secrets). Every entry here sets env_file explicitly. bash 3.2 safe.
# shellcheck shell=bash

# deploy_compose_names: <x> of each `- path: compose/<x>.yml` line, in file order.
deploy_compose_names() {
  local top="$BE_DIR/deploy/docker-compose.yml"
  [ -f "$top" ] || die "not found: $top"
  sed -nE 's#^[[:space:]]*-[[:space:]]*path:[[:space:]]*["'\'']?compose/([A-Za-z0-9_.-]+)\.yml["'\'']?[[:space:]]*$#\1#p' "$top"
}

# _masks_path <name>: the extra include path line of a generated host-.env mask fragment, if any.
_masks_path() {
  local f
  f="$(masks_file "$1")"
  [ ! -f "$f" ] || printf '      - "%s"\n' "$f"
}

_compose_body() {
  local name
  printf '# Generated by docker-development - do not edit.\nname: %s\ninclude:\n' "$PROJECT_NAME"
  for name in $1; do
    printf '  - path:\n      - "%s"\n      - "%s"\n' "$BE_DIR/deploy/compose/$name.yml" "$SELF_DIR/compose/$name.dev.yaml"
    _masks_path "$name"
    printf '    project_directory: "%s"\n    env_file: "%s"\n' "$BE_DIR/deploy" "$GEN_DIR/compose.env"
  done
  printf '  - path:\n      - "%s"\n' "$SELF_DIR/compose/dev-extras.yaml"
  _masks_path dev-extras
  printf '    project_directory: "%s"\n    env_file: "%s"\n' "$BE_DIR/deploy" "$GEN_DIR/compose.env"
}

render_compose() {
  local names name
  check_path_chars "$BE_DIR" "$SELF_DIR" "$GEN_DIR"
  names="$(deploy_compose_names)" || exit 1
  [ -n "$names" ] || die "no '- path: compose/<x>.yml' include found in $BE_DIR/deploy/docker-compose.yml"
  for name in $names; do
    [ -f "$BE_DIR/deploy/compose/$name.yml" ] || die "deploy/docker-compose.yml includes compose/$name.yml, which does not exist"
    [ -f "$SELF_DIR/compose/$name.dev.yaml" ] ||
      die "deploy/compose/$name.yml has no dev overlay docker-development/compose/$name.dev.yaml - add one (without it its services would read deploy/env/*.env, the real secrets)"
  done
  [ -f "$SELF_DIR/compose/dev-extras.yaml" ] || die "missing $SELF_DIR/compose/dev-extras.yaml"
  ensure_gen_dir
  # shellcheck disable=SC2086  # word-split compose names on purpose
  render_env_masks $names dev-extras
  _write_rendered "$GEN_DIR/compose.yaml" _compose_body "$names"
}

# render_all: secrets -> env files -> compose.yaml (what `./project render` and `up` run).
render_all() {
  check_path_chars "$BE_DIR" "$SELF_DIR" "$GEN_DIR" "$FE_DIR"
  ensure_secrets
  render_env_files
  render_compose
}
